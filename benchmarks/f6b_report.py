"""Build the F6-b results JSON from a cases file (bench or rescored output).

Aggregates per engine x time axis x image type, counting leads an engine did
not return as `lead_missing`, plus diagnostics (lag, amplitude, placement) and
median wall time. Metadata (engines, commits, data manifest) is copied from the
bench's own results JSON (--meta). Only observed numbers; not clinical
validation.
"""

import argparse
import json
import statistics
import sys
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from f6b_kaggle_bench import LAG_SLACK_S, aggregate, git_rev, percentile, with_missing_leads

# from the competition's data-description page (checked 2026-09-25); codes
# 0002, 0007 and 0008 do not exist in the train split
IMAGE_TYPES = {
    "0001": "original color image generated by ECG-image-kit",
    "0003": "printed in color, scanned in color",
    "0004": "printed in color, scanned in black and white",
    "0005": "mobile photo of a color printout",
    "0006": "mobile photo of the ECG on a laptop screen",
    "0009": "mobile photo of a stained and soaked printout",
    "0010": "mobile photo of a printout with extensive damage",
    "0011": "color scan of a printout with mold",
    "0012": "black-and-white scan of a printout with mold",
}
META_KEYS = (
    "scope",
    "calibration_note",
    "engine_duration_s_assumed",
    "rhythm_lead",
    "engines",
    "python",
    "machine",
    "data",
)


def build(records: list[dict], meta: dict) -> dict:
    groups: dict[str, list[dict]] = defaultdict(list)
    for r in records:
        for arm, cs in r["arms"].items():
            for c in with_missing_leads(cs):
                groups[f"{r['engine']}|{arm}|ALL"].append(c)
                groups[f"{r['engine']}|{arm}|{r['image_type']}"].append(c)
    diagnostics = {}
    for k, v in sorted(groups.items()):
        ok = [c for c in v if c.get("status") == "ok"]
        if ok:
            diagnostics[k] = {
                "median_abs_best_lag_s": percentile(
                    [abs(c["best_lag_s"]) for c in ok if c.get("best_lag_s") is not None], 50
                ),
                "median_engine_placement_s": percentile(
                    [
                        c["engine_placement_s"]
                        for c in ok
                        if c.get("engine_placement_s") is not None
                    ],
                    50,
                ),
                "median_coverage": percentile([c["coverage"] for c in ok], 50),
            }
    walls: dict[str, list[float]] = defaultdict(list)
    for r in records:
        if r.get("wall_s"):
            walls[f"{r['engine']}|{r['image_type']}"].append(r["wall_s"])
    return {
        "generated": datetime.now(UTC).isoformat(),
        **{k: meta.get(k) for k in META_KEYS},
        "bench_commit": meta.get("our_commit"),
        "report_commit": git_rev(Path(__file__).resolve().parent.parent),
        "lag_slack_s": LAG_SLACK_S,
        "image_types": {t: IMAGE_TYPES.get(t) for t in sorted({r["image_type"] for r in records})},
        "image_type_source": "Kaggle competition data-description page (kaggle API)",
        "missing_lead_policy": "leads an engine did not return count as status lead_missing",
        "aggregates": {k: aggregate(v) for k, v in sorted(groups.items())},
        "diagnostics": diagnostics,
        "median_wall_s": {k: statistics.median(v) for k, v in sorted(walls.items())},
        "grids": {
            f"{r['record']}-{r['image_type']}": r["grid"] for r in records if r["engine"] == "ahus"
        },
        "cases": records,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", type=Path, required=True, help="cases jsonl")
    ap.add_argument("--meta", type=Path, required=True, help="bench results json (metadata)")
    ap.add_argument("--types", nargs="*", default=None, help="image variants NNNN (default all)")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    records = [json.loads(line) for line in args.cases.read_text().splitlines()]
    if args.types:
        records = [r for r in records if r["image_type"] in args.types]
    res = build(records, json.loads(args.meta.read_text()))
    args.out.write_text(json.dumps(res, indent=2), encoding="utf-8")

    def fmt(v: object, d: int = 3) -> str:
        return f"{v:.{d}f}" if isinstance(v, float) else "–"

    print("| motor | eje | tipo | ok/filas | r@lag med [IQR] | SNR dB med | amp med | no-ok |")
    print("|---|---|---|---|---|---|---|---|")
    for k, a in res["aggregates"].items():
        e, arm, t = k.split("|")
        lo, hi = a["iqr_r_at_lag"]
        bad = ", ".join(f"{s} {n}" for s, n in sorted(a["statuses"].items()) if s != "ok")
        print(
            f"| {e} | {arm} | {t} | {a['n_ok']}/{a['n_rows']} | {fmt(a['median_r_at_lag'])} "
            f"[{fmt(lo, 2)}–{fmt(hi, 2)}] | {fmt(a['median_snr_db'], 1)} | "
            f"{fmt(a['median_amp_ratio'], 2)} | {bad} |"
        )
    print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
